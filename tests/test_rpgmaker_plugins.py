def test_full_flow_translates_backs_up_and_restores_plugins(tmp_path, monkeypatch, fake_ollama):
    import app_modern
    import providers
    from test_app import make_bridge, make_rpgmaker_game, run_sync
    game = make_rpgmaker_game(tmp_path / "game")
    js = game / "www" / "js"
    js.mkdir(exist_ok=True)
    original = ("var $plugins =\n[\n" + json.dumps(PLUGINS[0], separators=(",", ":")) + "\n];\n").encode("utf-8")
    (js / "plugins.js").write_bytes(original)
    bridge = make_bridge(tmp_path, monkeypatch, model="ollama")
    cfg = providers.ProviderConfig(ollama_host=fake_ollama)
    monkeypatch.setattr(app_modern.prov, "load_provider_config", lambda: cfg)
    bridge._select_game(str(game))
    run_sync(bridge, "analyze")
    run_sync(bridge, "translate")
    text = (js / "plugins.js").read_text(encoding="utf-8")
    assert "TR(Defend)" in text and '"Quests"' not in text and "Menu_BG" in text and "questLog" in text
    backup = next((game / "_capri_backups").iterdir())
    assert (backup / "www" / "js" / "plugins.js").read_bytes() == original
    bridge._restore_originals(bridge._game)
    assert (js / "plugins.js").read_bytes() == original


def test_mz_plugin_command_arguments(tmp_path):
    """MZ eklenti komutu (357): "message"/"title" argümanları çevrilir, resim/anahtar argümanları dokunulmaz."""
    data = tmp_path / "data"
    data.mkdir()
    cmd = {"code": 357, "indent": 0, "parameters": ["PopupPlugin", "show", "Show popup",
                                                     {"message": "You found a key!", "title text": "Notice",
                                                      "picture": "Popup_BG", "switchId": "3"}]}
    mapdata = {"events": [None, {"pages": [{"list": [cmd, {"code": 0, "parameters": []}]}]}]}
    (data / "Map001.json").write_text(json.dumps(mapdata), encoding="utf-8")
    found = sorted(t.original for t in rm.extract_texts_mv_mz(data, lambda _m: None))
    assert found == ["Notice", "You found a key!"]
    count = rm.write_translations_mv_mz(data, {"You found a key!": "Bir anahtar buldun!", "Notice": "Bildiri",
                                               "Popup_BG": "BOZUK", "show": "BOZUK"}, lambda _m: None)
    params = json.loads((data / "Map001.json").read_text(encoding="utf-8"))["events"][1]["pages"][0]["list"][0]["parameters"]
    assert count == 2 and params[3] == {"message": "Bir anahtar buldun!", "title text": "Bildiri",
                                        "picture": "Popup_BG", "switchId": "3"}
    assert params[:3] == ["PopupPlugin", "show", "Show popup"]


def test_random_plugin_files_roundtrip_safely(tmp_path):
    """Rastgele eklenti yapıları: çeviri yoksa dosya bayt bayt aynı; çeviri varsa yalnızca çıkarılan metinler değişir."""
    import random
    rnd = random.Random(1234)
    names = ["Help Text", "Title", "Command Name", "Picture File", "Switch ID", "Font Face", "Label", "Eval Code",
             "Message", "Icon Index", "Symbol", "Window Text", "Speed", "Vocab Attack"]
    values = ["Save Game", "Quest Log", "Menu_BG", "12", "true", "$gameSwitches.value(3)", "questLog", "x => x + 1",
              "Press OK", "img/pictures/a.png", "Ünlü «tırnak» \"çift\"", "", " ", "Line\nTwo", "A;B", "{}", "[]"]

    def value(depth=0):
        roll = rnd.random()
        if depth < 2 and roll < 0.15:
            return json.dumps({rnd.choice(names): value(depth + 1) for _ in range(rnd.randint(1, 3))},
                              ensure_ascii=False, separators=(",", ":"))
        if depth < 2 and roll < 0.25:
            return json.dumps([value(depth + 1) for _ in range(rnd.randint(0, 3))], ensure_ascii=False,
                              separators=(",", ":"))
        return rnd.choice(values)

    for case in range(40):
        root = tmp_path / f"g{case}"
        data = root / "data"
        data.mkdir(parents=True)
        (root / "js").mkdir()
        plugins = [{"name": f"P{i}", "status": rnd.random() > 0.2, "description": "",
                    "parameters": {rnd.choice(names) + str(k): value() for k in range(rnd.randint(0, 6))}}
                   for i in range(rnd.randint(1, 5))]
        body = "var $plugins =\n[\n" + ",\n".join(json.dumps(p, ensure_ascii=False, separators=(",", ":")) for p in plugins) + "\n];\n"
        path = root / "js" / "plugins.js"
        path.write_bytes(body.encode("utf-8"))
        texts = [t.original for t in rm.extract_plugin_texts(data, lambda _m: None)]
        assert rm.write_plugin_translations(data, {}, lambda _m: None) == 0
        assert rm.write_plugin_translations(data, {t: t for t in texts}, lambda _m: None) == 0
        assert path.read_bytes() == body.encode("utf-8")
        translated = {t: "TR " + t for t in texts}
        rm.write_plugin_translations(data, translated, lambda _m: None)
        after = path.read_text(encoding="utf-8")
        start = after.index("[")
        parsed = json.loads(after[start:after.rindex("]") + 1])
        assert [p["name"] for p in parsed] == [p["name"] for p in plugins]
        for old, new in zip(plugins, parsed):
            assert old.keys() == new.keys() and old["parameters"].keys() == new["parameters"].keys()
        for risky in ("Menu_BG", "$gameSwitches.value(3)", "questLog", "x => x + 1", "img/pictures/a.png"):
            assert after.count(risky) == body.count(risky), risky
