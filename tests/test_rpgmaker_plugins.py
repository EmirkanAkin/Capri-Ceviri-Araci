"""RPG Maker MV/MZ eklenti parametreleri (js/plugins.js): yalnızca arayüz yazıları çevrilir, kod/dosya/anahtar değil."""
import json
from pathlib import Path

import engine_rpgmaker as rm
from test_app import fake_ollama  # noqa: F401 (fixture)

PLUGINS = [
    {"name": "MenuLabels", "status": True, "description": "Menü yazıları",
     "parameters": {"Save Command Text": "Save Game", "Quest Window Title": "Quests",
                    "Help Text": "Press \\C[2]OK\\C[0] to continue.", "Picture File": "Menu_BG",
                    "Font Face": "GameFont", "Switch ID": "12", "Show Text": "true",
                    "Eval Text": "$gameVariables.value(5) > 2",
                    "Item Text Struct": json.dumps({"Label": "Potion box", "Icon Index": "176"}, separators=(",", ":")),
                    "Labels List": json.dumps(["Attack", "Defend"], separators=(",", ":")),
                    "Command Symbol": "questLog"}},
    {"name": "Disabled", "status": False, "description": "", "parameters": {"Title Text": "Hidden Thing"}},
    {"name": "Other", "status": True, "description": "", "parameters": {"Speed": "4"}},
]


def make_game(tmp_path, bom=True):
    data = tmp_path / "www" / "data"
    data.mkdir(parents=True)
    (data / "System.json").write_text(json.dumps({"gameTitle": "Demo", "terms": {}}), encoding="utf-8")
    js = tmp_path / "www" / "js"
    js.mkdir()
    body = ("// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n"
            + ",\n".join(json.dumps(p, ensure_ascii=False, separators=(",", ":")) for p in PLUGINS) + "\n];\n")
    (js / "plugins.js").write_bytes((b"\xef\xbb\xbf" if bom else b"") + body.encode("utf-8"))
    return data, js / "plugins.js"


def test_only_display_text_parameters_are_extracted(tmp_path):
    data, _ = make_game(tmp_path)
    found = sorted(t.original for t in rm.extract_plugin_texts(data, lambda _m: None))
    assert found == sorted(["Save Game", "Quests", "Press \\C[2]OK\\C[0] to continue.", "Potion box", "Attack", "Defend"])
    assert all(t.context == "plugin" for t in rm.extract_plugin_texts(data, lambda _m: None))
    texts = {t.original for t in rm.extract_texts_mv_mz(data, lambda _m: None)}
    assert "Quests" in texts and "Demo" in texts


def test_plugin_translations_keep_structure_code_and_other_plugins(tmp_path):
    data, path = make_game(tmp_path)
    before = path.read_bytes()
    tr = {"Save Game": "Oyunu Kaydet", "Quests": "Görevler", "Press \\C[2]OK\\C[0] to continue.":
          "Devam etmek için \\C[2]OK\\C[0] tuşuna bas.", "Potion box": "İksir kutusu", "Attack": "Saldır",
          "Defend": "Savun", "Menu_BG": "BOZUK", "GameFont": "BOZUK", "questLog": "BOZUK", "Hidden Thing": "BOZUK",
          "$gameVariables.value(5) > 2": "BOZUK"}
    assert rm.write_plugin_translations(data, tr, lambda _m: None) == 6
    raw = path.read_bytes()
    assert raw.startswith(b"\xef\xbb\xbf") and b"BOZUK" not in raw
    text = raw.decode("utf-8-sig")
    lines, old_lines = text.split("\n"), before.decode("utf-8-sig").split("\n")
    assert lines[:4] == old_lines[:4] and lines[-2:] == old_lines[-2:], "başlık ve kapanış aynı"
    assert lines[5] == old_lines[5] and lines[6] == old_lines[6], "değişmeyen eklenti satırları bayt bayt aynı"
    plugin = json.loads(lines[4].rstrip(","))
    params = plugin["parameters"]
    assert params["Quest Window Title"] == "Görevler" and params["Picture File"] == "Menu_BG"
    assert json.loads(params["Item Text Struct"]) == {"Label": "İksir kutusu", "Icon Index": "176"}
    assert json.loads(params["Labels List"]) == ["Saldır", "Savun"]
    assert rm.write_plugin_translations(data, {}, lambda _m: None) == 0


