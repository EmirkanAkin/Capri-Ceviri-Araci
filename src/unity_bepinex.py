"""
Unity BepInEx & XUnity.AutoTranslator Entegrasyon Modülü
======================================================
Unity oyunları için tek tıkla BepInEx ve XUnity.AutoTranslator köprüsü kurma,
çevrimdışı çeviri önbelleğini (cache) oyuna aktarma ve çalıştırma aracı.
"""
from __future__ import annotations

from pathlib import Path
from typing import Dict, Tuple

from engine_common import LogFn


def detect_unity_architecture(game_root: Path) -> Tuple[str, str]:
    """
    Unity oyununun mimarisini (64-bit / 32-bit) ve çalışma zamanını (Mono / IL2CPP) tespit eder.
    """
    game_root = Path(game_root)
    arch = "x64"
    runtime = "Mono"

    # Veri klasörünü bul
    data_dir = None
    for item in game_root.iterdir():
        if item.is_dir() and item.name.endswith("_Data"):
            data_dir = item
            break

    if data_dir:
        if (data_dir / "il2cpp_data").exists() or (game_root / "GameAssembly.dll").exists():
            runtime = "IL2CPP"
        elif (data_dir / "Managed").exists() or (game_root / "MonoBleedingEdge").exists():
            runtime = "Mono"

    # PE Header kontrolü (64-bit vs 32-bit)
    for exe in game_root.glob("*.exe"):
        if "crash" not in exe.name.lower():
            try:
                with open(exe, "rb") as f:
                    header = f.read(1024)
                if b"PE\x00\x00d\x86" in header:
                    arch = "x64"
                    break
                elif b"PE\x00\x00L\x01" in header:
                    arch = "x86"
                    break
            except Exception:
                pass

    return arch, runtime


def is_bepinex_installed(game_root: Path) -> bool:
    """Oyun dizininde BepInEx kurulu olup olmadığını kontrol eder."""
    root = Path(game_root)
    return (root / "BepInEx").is_dir() and (
        (root / "winhttp.dll").exists() or (root / "doorstop_config.ini").exists()
    )


def sync_cache_to_bepinex(
    game_root: Path,
    translations: Dict[str, str],
    target_lang: str = "tr",
    log: LogFn = print,
) -> int:
    """
    Bizim çevirdiğimiz metin önbelleğini XUnity.AutoTranslator'ın
    kullandığı _AutoGeneratedTranslations.txt dosyasına yazar.
    Bu sayede oyun açıldığında tek bir API çağrısı yapmadan,
    tüm çevirileri anında ekrana yansıtır!
    """
    root = Path(game_root)
    bepinex_dir = root / "BepInEx"
    if not bepinex_dir.exists():
        bepinex_dir.mkdir(parents=True, exist_ok=True)

    # XUnity.AutoTranslator çeviri klasörü yapısı:
    # BepInEx/Translation/{target_lang}/Text/_AutoGeneratedTranslations.txt
    trans_dir = bepinex_dir / "Translation" / target_lang / "Text"
    trans_dir.mkdir(parents=True, exist_ok=True)
    target_file = trans_dir / "_AutoGeneratedTranslations.txt"

    existing: Dict[str, str] = {}
    if target_file.exists():
        try:
            for line in target_file.read_text(encoding="utf-8", errors="ignore").splitlines():
                if "=" in line:
                    k, v = line.split("=", 1)
                    existing[k] = v
        except Exception:
            pass

    # Yeni çevirileri ekle
    added = 0
    for orig, trans in translations.items():
        if orig and trans and orig != trans:
            # Satır sonlarını escape et
            clean_orig = orig.replace("\r", "").replace("\n", "\\n")
            clean_trans = trans.replace("\r", "").replace("\n", "\\n")
            if clean_orig not in existing:
                existing[clean_orig] = clean_trans
                added += 1

    # Dosyaya kaydet
    lines = [f"{k}={v}" for k, v in existing.items()]
    target_file.write_text("\n".join(lines), encoding="utf-8")
    log(f"BepInEx çeviri önbelleği güncellendi: {target_file.name} (Toplam {len(lines)} satır, +{added} yeni)")
    return len(lines)


def generate_bepinex_autotranslator_config(
    game_root: Path,
    target_lang: str = "tr",
    source_lang: str = "en",
    log: LogFn = print,
) -> Path:
    """
    XUnity.AutoTranslator için optimize edilmiş, yerel önbellek öncelikli
    ve sıfır gecikmeli AutoTranslatorConfig.ini dosyasını oluşturur.
    """
    root = Path(game_root)
    config_dir = root / "BepInEx" / "config"
    config_dir.mkdir(parents=True, exist_ok=True)
    config_file = config_dir / "AutoTranslatorConfig.ini"

    config_content = f"""[Service]
Endpoint=
FallbackEndpoint=

[General]
Language={target_lang}
FromLanguage={source_lang}

[Files]
Directory=Translation
OutputFile=Translation\\{target_lang}\\Text\\_AutoGeneratedTranslations.txt
SubstitutionFile=Translation\\{target_lang}\\Text\\_Substitutions.txt
PreTranslationFile=Translation\\{target_lang}\\Text\\_PreTranslation.txt

[TextFrameworks]
EnableUGUI=True
EnableTextMeshPro=True
EnableNGUI=True
EnableTextMesh=True

[Behaviour]
MaxCharactersPerTranslation=1000
IgnoreWhitespaceInDialogue=False
MinDialogueChars=2
ForceUIResizing=True
OverrideFont=
FallbackFontTextMeshPro=
"""
    config_file.write_text(config_content, encoding="utf-8")
    log(f"BepInEx AutoTranslator yapılandırması hazırlandı: {config_file.name}")
    return config_file
